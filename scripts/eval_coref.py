def judge(query: str, got: str, kind: str, must: list, must_not: list) -> tuple[bool, str]:
    """含むべき語 / 入ってはいけない語で機械的に判定する。完全一致では測れない。"""
    leaked = [w for w in must_not if w in got]
    if leaked:
        return False, "余計な語を足した: " + ", ".join(leaked)
    missing = [w for w in must if w not in got]
    if missing:
        return False, "含むべき語が無い: " + ", ".join(missing)
    if kind == "rewrite" and got == query:
        return False, "書き換えていない"
    return True, ""


async def main():
    passed = 0
    missed = []
    leaks = 0
    for hist, q, kind, must, must_not, note in CASES:
        got = await resolve(q, hist)
        ok, why = judge(q, got, kind, must, must_not)
        passed += ok
        if not ok:
            missed.append((kind, q, got, why, note))
            leaks += why.startswith("余計な語")
        tail = "\n     " + why if not ok else ""
        print(f"{'OK' if ok else 'NG'} [{kind}] {q!r}\n     -> {got!r}{tail}")

    rew = sum(1 for c in CASES if c[2] == "rewrite")
    print(f"\n正解 {passed}/{len(CASES)}(model は非決定的。揺れは再実行して記録する)")
    print(f"  書き換えるべきもの {rew} 件 / 素通しすべきもの {len(CASES) - rew} 件")
    print(f"  規約の質問へ注文番号や商品名を足した件数: {leaks}"
          "(0 でないと一般的な規約検索が当たらなくなる)")
    if missed:
        print("\n外した事例:")
        for kind, q, got, why, note in missed:
            print(f"  [{kind}] {q!r} -> {got!r}\n      {why} / {note}")


if __name__ == "__main__":
    asyncio.run(main())
