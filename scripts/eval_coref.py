"""指示対象の解決のラベル付き評価。書き換えるべきものと素通しすべきものを両方測る。上流の呼び出しが必要。

書き下しは純粋なプロンプトの出力なので、単体テストでは正しさを固定できない
(上流を差し替えれば自分で書いた期待値をなぞるだけになる)。代わりに履歴付きの
サンプルを実際に流し、**含むべき語が入ったか / 入ってはいけない語が入っていないか**で
機械的に判定する。同じ意味の文が何通りもあるので、完全一致では測れない。

2 種類を必ず入れる。

- rewrite: 指示語を含む発話。履歴の対象が入ること。対象が特定の注文なら注文番号も入ること
- passthrough: すでに完結した発話。**直前に注文の話をしていても注文番号を足さないこと**。
  規約全般の質問に注文番号が付くと、その注文に限った検索へ化けて一般的な規約が引けなくなる。
  こちらが崩れる方が実害が大きいので、素通しの事例を意図的に多く入れてある。

実行: PYTHONUTF8=1 PYTHONPATH=. uv run --env-file .env python scripts/eval_coref.py
"""
